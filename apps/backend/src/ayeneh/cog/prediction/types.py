"""Predictive Cognitive types for the Ayeneh COG architecture (COG-14).

Defines PredictionObject, ScenarioObject, and supporting structures
that model probabilistic simulations of future cognitive states.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import Enum
from typing import Any


# ---------------------------------------------------------------------------
# Catalogue enumerations
# ---------------------------------------------------------------------------

PREDICTION_HORIZONS: list[str] = [
    'next_conversation', 'current_project', 'weeks', 'months', 'years',
]

PREDICTION_LIFECYCLE_STATES: list[str] = [
    'candidate', 'validated', 'confirmed', 'refuted', 'revised', 'historical',
]


# ---------------------------------------------------------------------------
# Domain and horizon enums
# ---------------------------------------------------------------------------

class PredictionDomain(str, Enum):
    """Domains in which predictions can be made."""

    BEHAVIOR = 'behavior'
    LEARNING = 'learning'
    PROJECTS = 'projects'
    DECISION_MAKING = 'decision_making'
    IDENTITY_EVOLUTION = 'identity_evolution'
    NARRATIVE_EVOLUTION = 'narrative_evolution'
    GOAL_COMPLETION = 'goal_completion'
    HABITFORMATION = 'habit_formation'
    REALITY_CALIBRATION = 'reality_calibration'
    META_COGNITIVE_DEVELOPMENT = 'meta_cognitive_development'


class PredictionHorizon(str, Enum):
    """Temporal horizons for predictions."""

    IMMEDIATE = 'immediate'
    SHORT_TERM = 'short_term'
    MEDIUM_TERM = 'medium_term'
    LONG_TERM = 'long_term'
    LIFETIME = 'lifetime'


# ---------------------------------------------------------------------------
# PredictionObject — probabilistic forecast of a cognitive state
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class PredictionObject:
    """A probabilistic forecast of a future cognitive state.

    Predictions are generated by analyzing trajectories, patterns, and
    current state to project likely future developments.
    """

    identifier: str
    prediction_statement: str
    target_cognitive_object: str
    probability: float = 0.0
    confidence: float = 0.0
    assumptions: tuple[str, ...] = ()
    supporting_evidence: tuple[str, ...] = ()
    contradictory_evidence: tuple[str, ...] = ()
    prediction_horizon: str = ''  # next_conversation|current_project|weeks|months|years
    underlying_trajectories: tuple[str, ...] = ()
    active_hypotheses: tuple[str, ...] = ()
    risk_factors: tuple[str, ...] = ()
    creation_timestamp: datetime = field(default_factory=lambda: datetime.now(UTC))
    revision_history: tuple[dict[str, Any], ...] = ()
    specification_version: str = '1.0.0'


# ---------------------------------------------------------------------------
# ScenarioObject — alternative future state
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class ScenarioObject:
    """An alternative future scenario for cognitive development.

    Scenarios represent plausible alternative paths that cognitive
    structures might take, with associated probabilities and assumptions.
    """

    scenario_id: str
    description: str
    probability: float = 0.0
    supporting_evidence: tuple[str, ...] = ()
    assumptions: tuple[str, ...] = ()
    uncertainties: tuple[str, ...] = ()


# ---------------------------------------------------------------------------
# Early Warning
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class EarlyWarning:
    """An early warning signal of impending cognitive change.

    Detected from pattern instabilities, trajectory anomalies, or
    conflicting evidence that suggests upcoming transitions.
    """

    warning_id: str
    description: str
    severity: float = 0.0  # 0.0-1.0
    evidence: tuple[str, ...] = ()
    recommended_attention: str = ''


# ---------------------------------------------------------------------------
# Result container
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class PredictionResult:
    """Output of the COG-14 Predictive Cognitive Engine pipeline."""

    predictions: dict[str, PredictionObject]
    scenarios: list[ScenarioObject]
    early_warnings: list[EarlyWarning]
    total_extracted: int = 0
