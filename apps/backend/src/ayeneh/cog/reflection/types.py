"""Reflection Engine types for the Ayeneh COG architecture (COG-12).

Defines ReflectionObject, InsightObject, BlindSpot, and supporting structures
that model evidence-based observations about cognitive structures.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Any


# ---------------------------------------------------------------------------
# Catalogue enumerations
# ---------------------------------------------------------------------------

REFLECTION_SCOPES: list[str] = [
    'project', 'career', 'relationships', 'identity', 'life_trajectory',
]

GRANULARITY_LEVELS: list[str] = [
    'micro', 'session', 'weekly', 'project',
    'relationship', 'identity', 'life',
]

LIFECYCLE_STATES: list[str] = [
    'candidate', 'provisional', 'validated', 'canonical', 'revised', 'historical',
]

VALIDATION_METHODS: list[str] = [
    'changed_language', 'behavior_change',
    'narrative_revision', 'belief_revision',
]


# ---------------------------------------------------------------------------
# ReflectionObject — evidence-based observation about a cognitive structure
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class ReflectionObject:
    """An evidence-based observation about a cognitive structure.

    Reflections are generated by the ReflectionEngine from evidence, patterns,
    narratives, and beliefs. They capture descriptive observations that may
    or may not have been explicitly recognized by the user.
    """

    identifier: str
    reflection_statement: str
    scope: str = ''  # project|career|relationships|identity|life_trajectory
    temporal_coverage: str = ''
    confidence: float = 0.0
    supporting_evidence: tuple[str, ...] = ()
    supporting_patterns: tuple[str, ...] = ()
    supporting_narratives: tuple[str, ...] = ()
    supporting_beliefs: tuple[str, ...] = ()
    contradictory_evidence: tuple[str, ...] = ()
    granularity: str = 'session'  # micro|session|weekly|project|relationship|identity|life
    lifecycle_state: str = 'candidate'
    creation_timestamp: datetime = field(default_factory=lambda: datetime.now(UTC))
    revision_history: tuple[dict[str, Any], ...] = ()
    specification_version: str = '1.0.0'


# ---------------------------------------------------------------------------
# InsightObject — user-recognized cognitive structure
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class InsightObject:
    """Evidence that the USER has genuinely recognized a cognitive structure.

    Unlike ReflectionObject (which is engine-generated), Insights represent
    moments where the user has explicitly articulated awareness of a pattern,
    belief, or behavioral tendency.
    """

    identifier: str
    insight_statement: str
    confidence: float = 0.0
    validation_method: str = ''  # changed_language|behavior_change|narrative_revision|belief_revision
    evidence: tuple[str, ...] = ()
    creation_timestamp: datetime = field(default_factory=lambda: datetime.now(UTC))


# ---------------------------------------------------------------------------
# BlindSpot — cognitive structure absent from awareness
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class BlindSpot:
    """A cognitive structure influencing behavior but absent from explicit awareness.

    Blind spots are detected when behavioral consistency, narrative recurrence,
    or cross-context appearance coexist with lack of explicit recognition.
    """

    identifier: str
    description: str
    estimated_impact: float = 0.0
    evidence: tuple[str, ...] = ()
    behavioral_consistency: float = 0.0
    narrative_recurrence: float = 0.0
    cross_context_appearance: float = 0.0
    lack_of_explicit_recognition: float = 0.0


# ---------------------------------------------------------------------------
# Result container
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class ReflectionResult:
    """Output of the COG-12 Reflection Engine pipeline."""

    reflections: dict[str, ReflectionObject]
    blind_spots: list[BlindSpot]
    total_extracted: int = 0
    insights: dict[str, InsightObject] = field(default_factory=dict)
    awakening_level: int = 0
