"""Reality Calibration types for the Ayeneh COG architecture (COG-15).

Defines CalibrationObject and MentalStoryObject — the core data structures
for distinguishing observed reality from interpretation, narrative, and belief.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Any


# ---------------------------------------------------------------------------
# Catalogue enumerations
# ---------------------------------------------------------------------------

CALIBRATION_STATES: list[str] = [
    'well_anchored',
    'moderately_anchored',
    'weakly_anchored',
    'highly_speculative',
    'contradicted',
    'under_revision',
    'unknown',
]

EVIDENCE_HIERARCHY: dict[int, str] = {
    1: 'direct_repeated_observation',
    2: 'repeated_behavior',
    3: 'independent_corroboration',
    4: 'consistent_self_report',
    5: 'interpretation',
    6: 'narrative',
    7: 'prediction',
    8: 'speculation',
}


# ---------------------------------------------------------------------------
# CalibrationObject — a single calibration-tracked entity
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class CalibrationObject:
    """A single event or claim calibrated against available evidence.

    Tracks how well-grounded an observed event is in direct evidence versus
    interpretation, narrative, and belief layers.
    """

    identifier: str
    observed_event: str
    available_evidence: tuple[str, ...] = ()
    interpretations: tuple[str, ...] = ()
    narratives: tuple[str, ...] = ()
    associated_beliefs: tuple[str, ...] = ()
    identity_involvement: float = 0.0
    prediction_involvement: float = 0.0
    confidence: float = 0.0
    evidence_quality: float = 0.0
    calibration_status: str = 'unknown'
    evidence_level: int = 8  # 1=strongest, 8=weakest
    creation_timestamp: datetime = field(default_factory=lambda: datetime.now(UTC))
    revision_history: tuple[dict[str, Any], ...] = ()
    specification_version: str = '1.0.0'


# ---------------------------------------------------------------------------
# MentalStoryObject — coherent internal world generated by the mind
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class MentalStoryObject:
    """A coherent internal story that organises reality into a meaningful framework.

    Mental stories are the mind's way of making sense of events. They carry
    actors, roles, rules, expected outcomes, and threats — and their distance
    from verifiable reality determines how much they distort perception.
    """

    story_id: str
    description: str
    actors: tuple[str, ...] = ()
    roles: tuple[str, ...] = ()
    rules: tuple[str, ...] = ()
    expected_outcomes: tuple[str, ...] = ()
    threats: tuple[str, ...] = ()
    desired_resolutions: tuple[str, ...] = ()
    supporting_narratives: tuple[str, ...] = ()
    underlying_beliefs: tuple[str, ...] = ()
    associated_emotions: tuple[str, ...] = ()
    identity_involvement: float = 0.0
    story_reality_distance: float = 0.0  # 0.0=fully anchored, 1.0=fully detached
    narrative_gravity: float = 0.0
    cognitive_fusion_level: float = 0.0
